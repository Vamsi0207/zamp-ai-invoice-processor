import { test, expect, type Page } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const fixture = fs.readFileSync(path.resolve('../fixtures/native_invoice.pdf'))
const data = JSON.parse(fs.readFileSync(path.resolve('../fixtures/synthetic_dataset.json'), 'utf8'))

async function upload(page: Page, name: string, method = 'manual') {
  await page.goto('/')
  await expect(page.getByText('Backend connected')).toBeVisible()
  await page.getByLabel('Extraction method', { exact: true }).selectOption(method)
  await page.getByLabel('Upload invoice PDF').setInputFiles({ name: `${name}.pdf`, mimeType: 'application/pdf', buffer: Buffer.concat([fixture, Buffer.from(`\n% browser ${name}`)]) })
  await expect(page).toHaveURL(/#\/runs\//)
  await expect(page.getByRole('heading', { name: 'Processing timeline' })).toBeVisible()
}

async function review(page: Page, number: string, quantity = 4, total = String(quantity * 100)) {
  await expect(page.getByRole('heading', { name: 'Review invoice details' })).toBeVisible()
  await page.getByLabel('Invoice number', { exact: true }).fill(number)
  await page.getByLabel('Vendor', { exact: true }).selectOption('DEMO-VENDOR')
  await page.getByLabel('Purchase order', { exact: true }).selectOption('DEMO-PO')
  await page.getByLabel('Currency', { exact: true }).selectOption('USD')
  await page.getByRole('button', { name: 'Add line' }).click()
  await page.getByLabel('PO line 1', { exact: true }).selectOption('L1')
  await page.getByLabel('Description', { exact: true }).fill('Office chairs')
  await page.getByLabel('Quantity', { exact: true }).fill(String(quantity))
  await page.getByLabel('Unit price', { exact: true }).fill('100.00')
  for (const label of ['Tax', 'Shipping', 'Discount']) await page.getByLabel(label, { exact: true }).fill('0.00')
  await page.getByLabel('Invoice total', { exact: true }).fill(total)
  await page.getByLabel('Reviewed by').fill('Demo Operator')
  await page.getByLabel('Review note').fill('Verified synthetic PDF and existing master-data references.')
  await page.getByRole('checkbox').check()
}

test('real browser and API: happy path, upload retry, partial invoices, duplicate and excessive value', async ({ page, request }) => {
  await upload(page, 'first')
  await page.getByRole('button', { name: 'Document text', exact: true }).click()
  await expect(page.locator('pre')).toContainText('SYN-001')
  await review(page, 'BROWSER-001')
  await page.screenshot({ path: 'test-results/review.png', fullPage: true })
  await page.getByRole('button', { name: 'Confirm & process' }).click()
  await expect(page.getByRole('heading', { name: 'Approved with confidence.' })).toBeVisible()
  await page.screenshot({ path: 'test-results/approved.png', fullPage: true })
  const firstURL = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Approved with confidence.' })).toBeVisible()
  await upload(page, 'first')
  await expect(page).toHaveURL(firstURL)
  const balance = await request.get('http://127.0.0.1:8911/purchase-orders/DEMO-PO/balance')
  expect((await balance.json()).allocated_cents).toBe(40000)

  await upload(page, 'partial')
  await review(page, 'BROWSER-002', 6)
  await page.getByRole('button', { name: 'Confirm & process' }).click()
  await expect(page.getByRole('heading', { name: 'Approved with confidence.' })).toBeVisible()
  await upload(page, 'business-duplicate')
  await review(page, 'browser 001')
  await page.getByRole('button', { name: 'Confirm & process' }).click()
  await expect(page.getByRole('heading', { name: 'This invoice was rejected.' })).toBeVisible()
  await expect(page.getByText('This vendor’s invoice number has already been submitted.')).toBeVisible()
  await upload(page, 'excessive')
  await review(page, 'BROWSER-EXCESS', 11)
  await page.getByRole('button', { name: 'Confirm & process' }).click()
  await expect(page.getByRole('heading', { name: 'This invoice was rejected.' })).toBeVisible()
  await expect(page.getByText('Cumulative invoice value exceeds the authorized PO ceiling.')).toBeVisible()
  expect((await (await request.get('http://127.0.0.1:8911/purchase-orders/DEMO-PO/balance')).json()).allocated_cents).toBe(100000)
  await page.goto('/#/history')
  await expect(page.getByRole('table')).toContainText('BROWSER-EXCESS')
  await page.getByRole('button', { name: 'Approved', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('BROWSER-001')
  await expect(page.getByRole('table')).not.toContainText('BROWSER-EXCESS')
})

test('missing PO blocks confirmation; real provider-not-configured failure can switch to manual review', async ({ page, request }) => {
  await upload(page, 'missing-po')
  await review(page, 'MISSING-PO')
  await page.getByLabel('Purchase order', { exact: true }).selectOption('')
  await page.getByRole('button', { name: 'Confirm & process' }).click()
  await expect(page.getByRole('heading', { name: 'Review invoice details' })).toBeVisible()
  const wid = page.url().split('/').pop()
  const response = await request.post(`http://127.0.0.1:8911/api/workflows/${wid}/review`, { data: { invoice: { ...data.invoices[0], po_id: null }, reviewer: 'Browser test', note: 'Missing PO check', confirmed: true } })
  expect(response.status()).toBe(422)
  await upload(page, 'missing-key', 'gemini')
  await expect(page.getByRole('alert')).toContainText('PROVIDER_NOT_CONFIGURED')
  await page.getByLabel('Retry extraction method').selectOption('manual')
  await page.getByRole('button', { name: 'Retry safely' }).click()
  await expect(page.getByRole('heading', { name: 'Review invoice details' })).toBeVisible()
  await expect(page.getByText('Attempt 2', { exact: false })).toBeVisible()
  await page.goto('/')
  await expect(page.getByText('Documents received', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/dashboard.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Invoice operations' })).toBeVisible()
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true })
  const overflow = await page.evaluate(() => Array.from(document.querySelectorAll('body *')).filter(el => el.getBoundingClientRect().right > window.innerWidth + 1).map(el => ({ tag: el.tagName, cls: el.className, width: Math.round(el.getBoundingClientRect().width), right: Math.round(el.getBoundingClientRect().right) })).slice(0, 15))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), JSON.stringify(overflow)).toBe(true)
})

test('upload modal and drag-and-drop both create real persisted runs', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Backend connected')).toBeVisible()
  await page.getByRole('button', { name: 'Upload invoice', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Upload an invoice' })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('Extraction method', { exact: true }).selectOption('manual')
  await dialog.getByLabel('Upload invoice PDF').setInputFiles({ name: 'modal.pdf', mimeType: 'application/pdf', buffer: Buffer.concat([fixture, Buffer.from('\n% modal')]) })
  await expect(page.getByRole('heading', { name: 'Review invoice details' })).toBeVisible()
  await expect(dialog).not.toBeVisible()
  await page.goto('/')
  const transfer = await page.evaluateHandle((bytes) => {
    const transfer = new DataTransfer()
    transfer.items.add(new File([new Uint8Array(bytes)], 'dropped.pdf', { type: 'application/pdf' }))
    return transfer
  }, Array.from(Buffer.concat([fixture, Buffer.from('\n% dropped')])) )
  await page.locator('.drop-zone').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(page.getByRole('heading', { name: 'Review invoice details' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'dropped.pdf', exact: true })).toBeVisible()
  await page.goto('/#/master-data')
  await page.getByRole('button', { name: 'Record receipt', exact: true }).click()
  await page.getByLabel('Quantity received').fill('1')
  await page.getByRole('button', { name: 'Save receipt', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Receipt exceeds ordered quantity')
})
